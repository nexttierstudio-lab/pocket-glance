"""Builds a copy of the site ready to put on your own domain, under /pocket_glance/.

    python tools/publish.py --domain example.com
    python tools/publish.py                       # reads the domain from SITE_DOMAIN
    python tools/publish.py --domain example.com --stubs   # for GitHub Pages (see below)

It writes:

    dist/                     upload or deploy everything in here, as is
      pocket_glance/          the whole site (homepage in every language, legal pages, fonts, images)
      .htaccess               for GoDaddy cPanel / Apache: https, www -> bare domain, / -> /pocket_glance/
      _redirects              the same redirects for Netlify
      index.html              fallback for hosts with no redirects: sends visitors on to /pocket_glance/
      privacy.html, es/, ...  only with --stubs: small pages that send the old top-level addresses on
                              to /pocket_glance/..., for hosts with no server redirects (GitHub Pages)
    dist.zip                  dist/ zipped, for uploading through cPanel File Manager

The repo itself is not changed, so GitHub Pages keeps serving the existing address. Only the
absolute addresses search engines read (canonical, hreflang, og:image) point at your domain;
every link a visitor clicks is relative, so the site works in any folder.
"""
import argparse
import os
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SUBPATH = "pocket_glance"
DIST = ROOT / "dist"
STATIC = ["fonts", "img"]  # the pages themselves come from tools/site/build.py
LEGAL = ["privacy.html", "terms.html", "help.html", "delete-data.html"]
LANG_FOLDERS = ["es", "pt", "fr", "de", "hi", "ar", "ja", "ko", "zh"]


def htaccess(domain):
    host = domain.replace(".", r"\.")
    return f"""# Pocket Glance on {domain}: the site lives in /{SUBPATH}/
# Generated by tools/publish.py. Goes in the domain's web root (public_html on GoDaddy cPanel).
Options -Indexes
DirectoryIndex index.html

<IfModule mod_rewrite.c>
RewriteEngine On

# Leave certificate checks alone (cPanel AutoSSL / Let's Encrypt).
RewriteRule ^\\.well-known/ - [L]

# Always https, always the bare domain (www.{domain} -> {domain}).
RewriteCond %{{HTTPS}} !=on [OR]
RewriteCond %{{HTTP_HOST}} !^{host}$ [NC]
RewriteRule ^(.*)$ https://{domain}/$1 [R=301,L]

# The bare domain opens the site.
RewriteRule ^$ /{SUBPATH}/ [R=301,L]

# Old top-level addresses (privacy.html, es/, ...) move to their place under /{SUBPATH}/.
RewriteCond %{{REQUEST_URI}} !^/{SUBPATH}(/|$)
RewriteCond %{{REQUEST_FILENAME}} !-f
RewriteCond %{{REQUEST_FILENAME}} !-d
RewriteRule ^(.*)$ /{SUBPATH}/$1 [R=301,L]
</IfModule>

<IfModule mod_expires.c>
ExpiresActive On
ExpiresByType font/ttf "access plus 1 year"
ExpiresByType image/webp "access plus 1 month"
ExpiresByType image/png "access plus 1 month"
ExpiresByType text/html "access plus 0 seconds"
</IfModule>
"""


def netlify_redirects():
    lines = [f"/  /{SUBPATH}/  301!"]
    lines += [f"/{page}  /{SUBPATH}/{page}  301" for page in LEGAL]
    lines += [f"/{code}/*  /{SUBPATH}/{code}/:splat  301" for code in LANG_FOLDERS]
    return "# Generated by tools/publish.py. Set the www domain to redirect to the bare one in Netlify.\n" + "\n".join(lines) + "\n"


def fallback_index(site_url):
    return f"""<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>Pocket Glance</title>
  <link rel="canonical" href="{site_url}">
  <meta http-equiv="refresh" content="0; url={SUBPATH}/">
  <script>location.replace("{SUBPATH}/" + location.search + location.hash);</script>
</head>
<body>
  <p><a href="{SUBPATH}/">Continue to Pocket Glance</a></p>
</body>
</html>
"""


def stub(site_url, path):
    """A page at an old top-level address that sends visitors to its new place."""
    depth = path.count("/")
    target = "../" * depth + f"{SUBPATH}/" + path.removesuffix("index.html")
    return f"""<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>Pocket Glance</title>
  <link rel="canonical" href="{site_url}{path.removesuffix('index.html')}">
  <meta name="robots" content="noindex">
  <meta http-equiv="refresh" content="0; url={target}">
  <script>location.replace("{target}" + location.search + location.hash);</script>
</head>
<body>
  <p><a href="{target}">Continue to Pocket Glance</a></p>
</body>
</html>
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--domain", default=os.environ.get("SITE_DOMAIN"), help="your domain, without www (or set SITE_DOMAIN)")
    ap.add_argument("--stubs", action="store_true", help="add redirect pages at the old top-level addresses")
    args = ap.parse_args()

    domain = (args.domain or "").strip().lower()
    for prefix in ("https://", "http://"):
        domain = domain.removeprefix(prefix)
    domain = domain.removeprefix("www.").strip("/")
    if not domain or "/" in domain or "." not in domain:
        sys.exit("Give your domain, for example: python tools/publish.py --domain example.com")

    site_url = f"https://{domain}/{SUBPATH}/"
    site = DIST / SUBPATH
    if DIST.exists():
        shutil.rmtree(DIST)
    site.mkdir(parents=True)

    print(f"Building for {site_url}")
    build = [sys.executable, str(ROOT / "tools" / "site" / "build.py"), "--site-url", site_url, "--out", str(site)]
    if subprocess.run(build, cwd=ROOT, stdout=subprocess.DEVNULL).returncode:
        sys.exit("Build failed, fix the error above and run again.")

    for name in STATIC:
        src = ROOT / name
        if src.is_dir():
            shutil.copytree(src, site / name)
        else:
            shutil.copy2(src, site / name)

    (DIST / ".htaccess").write_text(htaccess(domain), encoding="utf-8", newline="\n")
    (DIST / "_redirects").write_text(netlify_redirects(), encoding="utf-8", newline="\n")
    (DIST / "index.html").write_text(fallback_index(site_url), encoding="utf-8", newline="\n")

    if args.stubs:
        for path in LEGAL + [f"{code}/index.html" for code in LANG_FOLDERS]:
            out = DIST / path
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(stub(site_url, path), encoding="utf-8", newline="\n")

    archive = ROOT / "dist.zip"
    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED) as z:
        for path in sorted(DIST.rglob("*")):
            if path.is_file():
                z.write(path, path.relative_to(DIST).as_posix())

    files = sum(1 for p in DIST.rglob("*") if p.is_file())
    print(f"Wrote {files} files to {DIST}")
    print(f"Zipped them to {archive}")
    print(f"Live address once uploaded: {site_url}")


if __name__ == "__main__":
    main()
